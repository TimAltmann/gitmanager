//! XML-Entity-Kodierung für Toast-XML und Windows-Terminal-Konfiguration.

/// Escapt die fünf XML-Basiselemente. Reihenfolge ist unerheblich, da
/// zeichenweise gearbeitet wird.
pub fn escape(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for c in s.chars() {
        match c {
            '&' => out.push_str("&amp;"),
            '<' => out.push_str("&lt;"),
            '>' => out.push_str("&gt;"),
            '"' => out.push_str("&quot;"),
            '\'' => out.push_str("&apos;"),
            _ => out.push(c),
        }
    }
    out
}

/// Umkehrung von [`escape`]. `&amp;` zuletzt, damit nicht doppelt dekodiert wird.
pub fn unescape(s: &str) -> String {
    s.replace("&lt;", "<")
        .replace("&gt;", ">")
        .replace("&quot;", "\"")
        .replace("&apos;", "'")
        .replace("&amp;", "&")
}
